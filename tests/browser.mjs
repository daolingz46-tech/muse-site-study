import { chromium, expect } from "@playwright/test";
import { readFileSync, mkdirSync } from "node:fs";
const base = process.env.TEST_BASE_URL || "http://127.0.0.1:8787";
if (!/^http:\/\/(localhost|127\.0\.0\.1):/.test(base)) throw new Error("浏览器测试只允许本地服务，避免生成线上测试订单");
function assertLocal(url) { if (new URL(url).origin !== base) throw new Error("测试意外跳转到了外部网站，已停止"); }
const password = readFileSync("admin-access.local.txt", "utf8").match(/管理密码：(.+)/)[1].trim();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const errors = [];
try {
  mkdirSync("temp/evidence", { recursive: true });
  const customer = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ["clipboard-read", "clipboard-write"] });
  const page = await customer.newPage(); page.on("pageerror", e => errors.push(e.message));
  await page.goto(base); await page.waitForLoadState("networkidle");
  assertLocal(page.url()); await expect(page.getByText(/仅供学习|教学演示|非官方/)).toHaveCount(0);
  await page.getByRole("tab", { name: "Muse Token" }).click();
  await page.locator('input[name="token-plan"][value="100"]').check();
  await page.getByLabel("账号邀请码").fill("BROWSER-CHECK-INVITE");
  await page.getByRole("combobox", { name: "支付方式" }).selectOption("wechat");
  await page.getByRole("checkbox").check(); await page.getByRole("button", { name: "确认订单" }).click();
  await page.getByRole("checkbox").check(); await page.getByRole("button", { name: "继续下单", exact: true }).click({ timeout: 10000 });
  const code = page.getByRole("textbox", { name: "4 位订单码" }); await expect(code).toHaveValue(/^\d{4}$/);
  const codeText = await code.inputValue(); const link = page.url();
  await expect(page.getByRole("button", { name: /打开微信收款码/ })).toBeDisabled();
  await expect(page.getByRole("checkbox", { name: /我会在付款备注/ })).toBeDisabled();
  await page.getByRole("button", { name: "复制订单码", exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(codeText);
  await page.getByRole("checkbox", { name: /我会在付款备注/ }).check();
  await page.screenshot({ path: "temp/evidence/order-code-mobile.png", fullPage: true });
  await page.getByRole("button", { name: /打开微信收款码/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  const image = page.getByRole("img", { name: "微信收款码" }); await expect(image).toBeVisible();
  expect(await image.evaluate(img => img.complete && img.naturalWidth === 1254)).toBe(true);
  await page.screenshot({ path: "temp/evidence/payment-qr-mobile.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 320, height: 700 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "我已付款，通知店主核对" }).click();
  await expect(page.getByRole("heading", { name: "等待核实到账" })).toBeVisible();
  const otherDevice = await browser.newContext(); const lookup = await otherDevice.newPage();
  await lookup.goto(link); await expect(lookup.getByRole("heading", { name: "等待核实到账" })).toBeVisible();
  const adminContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const admin = await adminContext.newPage(); admin.on("pageerror", e => errors.push(e.message));
  await admin.goto(`${base}/admin/`); await admin.getByLabel("管理密码").fill(password); await admin.getByRole("button", { name: "登录工作台" }).click();
  await expect(admin.getByRole("heading", { name: "订单工作台" })).toBeVisible();
  await admin.getByRole("textbox", { name: "搜索订单" }).fill(codeText); await admin.getByRole("button", { name: "查询", exact: true }).click();
  const row = admin.locator("tbody tr").filter({ hasText: codeText }); await expect(row).toHaveCount(1);
  await row.getByRole("button", { name: "核实收款" }).click();
  await admin.getByLabel("支付交易单号").fill(`BROWSER-WECHAT-${Date.now()}`);
  await admin.getByRole("button", { name: "确定", exact: true }).click();
  await expect(row.getByRole("button", { name: "完成充值" })).toBeVisible();
  await lookup.getByRole("button", { name: "刷新订单状态" }).click(); await expect(lookup.getByRole("heading", { name: "已收款，处理中" })).toBeVisible();
  await admin.screenshot({ path: "temp/evidence/workbench-desktop.png", fullPage: true });
  await row.getByRole("button", { name: "完成充值" }).click(); await admin.getByRole("checkbox", { name: "我已为此邀请码完成充值" }).check();
  await admin.getByRole("button", { name: "确认已完成交付" }).click();
  await lookup.getByRole("button", { name: "刷新订单状态" }).click(); await expect(lookup.getByRole("heading", { name: "订单已完成" })).toBeVisible();
  await admin.setViewportSize({ width: 390, height: 844 }); await admin.screenshot({ path: "temp/evidence/workbench-mobile.png", fullPage: true });
  expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await admin.getByRole("button", { name: "退出", exact: true }).click(); await expect(admin.getByLabel("管理密码")).toBeVisible();
  const qr = await page.request.get(`${base}/api/payment-qr/alipay`); expect(qr.status()).toBe(200); expect(qr.headers()["content-type"]).toBe("image/png");
  expect(errors).toEqual([]);
  console.log("PASS: 手机复制门槛、备注确认、微信收款弹窗、支付宝图片、跨设备订单链接、管理员核款和交付、320/390px 响应式");
} finally { await browser.close(); }
