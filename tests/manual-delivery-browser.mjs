import { chromium, expect } from "@playwright/test";

const base = process.env.TEST_BASE_URL || "http://127.0.0.1:18935";
if (!/^http:\/\/(localhost|127\.0\.0\.1):/.test(base)) throw new Error("Only local mock tests are allowed");
const browser = await chromium.launch({ channel: "chrome", headless: true });
const order = { id: "mock-order", code: "0123", product: "gpt", title: "GPT · 一个月半价资格账号", amountCents: 1500, target: "buyer@example.com", method: "alipay", status: "processing", createdAt: Date.now(), reportedAt: null, reference: null };
const writes = [], errors = [];
let completed = false;
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", async route => {
    const url = new URL(route.request().url());
    if (url.origin !== base) return route.abort();
    if (!url.pathname.startsWith("/api/")) return route.continue();
    const path = url.pathname.replace("/api/admin/", "");
    let data = {};
    if (path === "orders") data = { orders: [{ ...order, status: completed ? "complete" : "processing" }], count: { total: 1 }, page: 0, summary: { total: 1, awaiting: 0, processing: completed ? 0 : 1, completed: completed ? 1 : 0, revenueCents: 1500, todayCents: 1500 } };
    else if (path === "visits") data = { summary: { total: 0, today: 0, last7Days: 0 }, recent: [] };
    else if (path === "email-status") data = { configured: true, attachments: true };
    else if (path === "tutorial") data = { title: "Muse 教程", blocks: [], updatedAt: null };
    else if (path === "catalog") data = { products: [] };
    else if (path === "inventory") data = { groups: [] };
    else if (path === "delivery-files") data = { files: [], sources: [{ goodsNo: "G88655555", instructions: "请使用电脑登录 ChatGPT 并检查半价优惠。" }, { goodsNo: "G75777360", instructions: "" }] };
    else if (["send-delivery", "confirm-external-delivery", "contact-buyer", "order-cost"].includes(path)) {
      writes.push({ path, ...route.request().postDataJSON() });
      if (["send-delivery", "confirm-external-delivery"].includes(path)) completed = true;
      data = { ok: true };
    } else throw new Error(`Unexpected API: ${path}`);
    await route.fulfill({ json: data });
  });
  await page.goto(`${base}/admin/`);
  const row = page.locator("tbody tr").filter({ hasText: "0123" });
  await row.getByRole("button", { name: "联系客户", exact: true }).click();
  await expect(page.getByText(/这是沟通邮件，发送后不会改变订单状态/)).toBeVisible();
  await page.getByLabel("邮件内容").fill("已经核对，请查收邮件");
  await page.getByRole("dialog").getByRole("button", { name: "发送邮件", exact: true }).click();
  await expect(row.getByText("待交付", { exact: true })).toBeVisible();
  await row.getByRole("button", { name: "手动发货", exact: true }).click();
  await page.getByLabel("卡密内容（必填）").fill("EXAMPLE-ACCOUNT");
  await expect(page.getByRole("button", { name: "发送邮件并标记已交付" })).toBeDisabled();
  await page.getByLabel("实际采购商品编号").selectOption("G88655555");
  await expect(page.getByLabel("该货源使用说明")).toHaveValue(/请使用电脑登录/);
  await expect(page.getByText("附带默认教程", { exact: true })).toHaveCount(0);
  await page.getByLabel("实际采购商品编号").selectOption("G75777360");
  await expect(page.getByLabel("该货源使用说明")).toHaveValue("");
  await expect(page.getByRole("button", { name: "发送邮件并标记已交付" })).toBeDisabled();
  await page.getByLabel("该货源使用说明").fill("这是当前货源的专属教程");
  await page.getByRole("button", { name: "发送邮件并标记已交付" }).click();
  await expect(row.getByText("已完成", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "补录采购成本 · 订单 0123" })).toBeVisible();
  await page.getByRole("dialog").getByRole("button", { name: "关闭" }).click();
  expect(writes.at(-1)).toMatchObject({ path: "send-delivery", goodsNo: "G75777360", instructions: "这是当前货源的专属教程" });
  completed = false;
  await page.reload();
  await page.setViewportSize({ width: 390, height: 844 });
  await row.getByRole("button", { name: "确认已交付", exact: true }).click();
  await expect(page.getByRole("button", { name: "确认完成，不重复发货" })).toBeDisabled();
  await page.getByLabel("核查备注").fill("已在发件箱核查，客户确认收到账号");
  await page.getByRole("checkbox", { name: "我已核查，确认商品已交付给此客户" }).check();
  await page.getByRole("button", { name: "确认完成，不重复发货" }).click();
  await expect(row.getByText("已完成", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "补录采购成本 · 订单 0123" })).toBeVisible();
  await page.getByLabel("货源商").fill("示例货源");
  await page.getByLabel("商品编号").fill("G88655555");
  await page.getByLabel("实际采购总成本（元）").fill("3.25");
  await page.getByRole("button", { name: "保存采购信息" }).click();
  expect(writes.at(-1)).toMatchObject({path:"order-cost",costCents:325});
  expect(writes.map(write => write.path)).toEqual(["contact-buyer", "send-delivery", "confirm-external-delivery", "order-cost"]);
  expect(errors).toEqual([]);
  console.log("PASS: GPT contact/manual delivery/external confirmation, source-specific guide and mobile controls");
} finally { await browser.close(); }
